-- supabase/sql/20260526_registered_device_foundation_d1.sql
-- C.S.V. BEACON — D1 Registered Device Foundation
-- Purpose:
--   All application access shall be tied to a registered device identity.
--   Offline permission is deliberately separate from general device approval.
--
-- Scope of this migration:
--   - Adds registered device table.
--   - Adds request/status/admin RPC foundation.
--   - Does not yet enforce a global frontend block.
--   - Does not yet enforce device approval inside every existing business RPC.
--   - Does not activate offline sync.

begin;

create extension if not exists pgcrypto;

create table if not exists public.csvb_registered_devices (
  id uuid primary key default gen_random_uuid(),

  -- Browser/PWA-generated durable public identifier.
  -- This is not a hardware serial number. It is generated by the application and stored locally on the device/browser profile.
  device_public_id text not null unique,

  device_label text,
  device_type text not null default 'unknown'
    check (device_type in ('desktop','laptop','tablet','smartphone','shared_workstation','unknown')),
  platform text,
  browser_language text,
  screen_summary text,
  user_agent_summary text,

  -- Access control status.
  status text not null default 'pending'
    check (status in ('pending','approved','blocked','revoked')),

  -- Access scope. Company/vessel are copied from the requesting user's profile.
  company_id uuid,
  vessel_id uuid,

  requested_by uuid,
  requested_at timestamptz not null default now(),

  approved_by uuid,
  approved_at timestamptz,

  blocked_by uuid,
  blocked_at timestamptz,

  revoked_by uuid,
  revoked_at timestamptz,

  last_user_id uuid,
  last_seen_at timestamptz,

  -- Offline capability is separate from general device approval.
  offline_allowed boolean not null default false,
  offline_allowed_modules text[] not null default array[]::text[],

  notes text,
  metadata jsonb not null default '{}'::jsonb,

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists idx_csvb_registered_devices_company_status
  on public.csvb_registered_devices(company_id, status);

create index if not exists idx_csvb_registered_devices_vessel_status
  on public.csvb_registered_devices(vessel_id, status);

create index if not exists idx_csvb_registered_devices_last_seen
  on public.csvb_registered_devices(last_seen_at desc nulls last);

create index if not exists idx_csvb_registered_devices_requested_by
  on public.csvb_registered_devices(requested_by);

alter table public.csvb_registered_devices enable row level security;

-- No broad direct table access. All normal access goes through SECURITY DEFINER RPCs.
drop policy if exists csvb_registered_devices_no_direct_access on public.csvb_registered_devices;
create policy csvb_registered_devices_no_direct_access
  on public.csvb_registered_devices
  for all
  to authenticated
  using (false)
  with check (false);

create or replace function public.csvb_device_touch_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists trg_csvb_registered_devices_updated_at on public.csvb_registered_devices;
create trigger trg_csvb_registered_devices_updated_at
before update on public.csvb_registered_devices
for each row
execute function public.csvb_device_touch_updated_at();

create or replace function public.csvb_device_current_profile()
returns table (
  user_id uuid,
  username text,
  role text,
  company_id uuid,
  vessel_id uuid
)
language sql
security definer
set search_path = public
as $$
  select
    p.id as user_id,
    p.username::text as username,
    p.role::text as role,
    p.company_id,
    p.vessel_id
  from public.profiles p
  where p.id = auth.uid();
$$;

create or replace function public.csvb_device_is_platform_admin()
returns boolean
language sql
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.profiles p
    where p.id = auth.uid()
      and p.role::text in ('super_admin','platform_owner')
  );
$$;

